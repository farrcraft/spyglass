//! The `spyglass` command: a thin front end over the `spyglass` library (ADR 0014). Output is
//! human-readable, or JSON with `--json` (`docs/specs/cli-json.md`).

use std::path::{Path, PathBuf};
use std::process::ExitCode;

use anyhow::{Context, Result, bail};
use clap::{Args, Parser, Subcommand};
use serde_json::{Value, json};
use spyglass::{LOCATE_BIOME_RADIUS, LOCATE_RADIUS, SaveReport, Scan, Session, World};

/// The `--json` format version (`docs/specs/cli-json.md`).
const JSON_FORMAT: u32 = 1;

/// How many hits human output lists; `--json` has them all.
const SHOWN: usize = 8;

#[derive(Parser)]
#[command(
    name = "spyglass",
    version,
    about = "Explore Minecraft: Java Edition seeds locally."
)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Find structures, biomes, slime chunks or the spawn for a seed, as `/locate` would.
    Locate {
        #[command(subcommand)]
        what: Locate,
    },
    /// Your world saves: list them, or see what spyglass makes of one.
    World {
        #[command(subcommand)]
        what: WorldCmd,
    },
}

#[derive(Subcommand)]
enum WorldCmd {
    /// Saves in the known launchers' folders.
    List {
        /// Where bundles are, to say which saves spyglass can answer for.
        #[arg(long, default_value = "bundles")]
        bundles: PathBuf,
        /// Print JSON (docs/specs/cli-json.md) instead of text.
        #[arg(long)]
        json: bool,
    },
    /// A save's seed, version, spawn and player, and anything that makes answers inexact.
    Info {
        /// The save's folder, or its folder name in a launcher's saves.
        save: String,
        /// Where bundles are, one directory per version.
        #[arg(long, default_value = "bundles")]
        bundles: PathBuf,
        /// Skip counting chunks generated by older versions (which reads every region file).
        #[arg(long)]
        quick: bool,
        /// Print JSON (docs/specs/cli-json.md) instead of text.
        #[arg(long)]
        json: bool,
    },
}

#[derive(Subcommand)]
enum Locate {
    /// The nearest structure: an id (`minecraft:mansion`) or a tag (`#minecraft:village`).
    Structure {
        /// Structure id or `#tag`.
        target: String,
        #[command(flatten)]
        common: Common,
        #[command(flatten)]
        from: From,
        /// Rings of placement cells to search; the game's `/locate` searches 100.
        #[arg(long, default_value_t = LOCATE_RADIUS)]
        radius: i32,
    },
    /// The nearest biome, searched in 3D from `--from`, as `/locate biome` does.
    Biome {
        /// Biome id, e.g. `minecraft:cherry_grove`.
        biome: String,
        #[command(flatten)]
        common: Common,
        #[command(flatten)]
        from: From,
        /// Search radius in blocks; the game's `/locate` searches 6400.
        #[arg(long, default_value_t = LOCATE_BIOME_RADIUS)]
        radius: i32,
    },
    /// Slime chunks near `--from`, nearest first.
    Slime {
        #[command(flatten)]
        common: Common,
        #[command(flatten)]
        from: From,
        /// Search radius in chunks.
        #[arg(long, default_value_t = 8)]
        radius: i32,
    },
    /// The chunk the game's world-spawn search starts from.
    Spawn {
        #[command(flatten)]
        common: Common,
    },
}

#[derive(Args)]
struct Common {
    /// The world seed: a number, or text hashed as the world-creation screen does.
    #[arg(long, allow_hyphen_values = true, required_unless_present = "world")]
    seed: Option<String>,
    /// A world save instead of a seed: its folder, or its folder name in a launcher's saves.
    /// Its seed and version are used, and anything that makes answers inexact is shown.
    #[arg(long, conflicts_with_all = ["seed", "bundle", "game_version"])]
    world: Option<String>,
    /// Game version of the bundle to use, from `--bundles`. Defaults to the newest there.
    #[arg(long)]
    game_version: Option<String>,
    /// A bundle directory to use instead of choosing one from `--bundles`.
    #[arg(long, conflicts_with = "game_version")]
    bundle: Option<PathBuf>,
    /// Where bundles are, one directory per version.
    #[arg(long, default_value = "bundles")]
    bundles: PathBuf,
    /// Print JSON (docs/specs/cli-json.md) instead of text.
    #[arg(long)]
    json: bool,
}

/// Where a search starts.
#[derive(Clone, Copy)]
enum Origin {
    At([i32; 3]),
    /// The single player of `--world`'s save.
    Player,
}

#[derive(Args)]
struct From {
    /// Where to search from: `x,y,z` or `x,z` (y 64), in blocks, or `player` for the single
    /// player of `--world`.
    #[arg(long, default_value = "0,64,0", allow_hyphen_values = true, value_parser = origin)]
    from: Origin,
}

fn origin(text: &str) -> Result<Origin, String> {
    if text == "player" {
        return Ok(Origin::Player);
    }
    let parts: Vec<i32> = text
        .split(',')
        .map(|p| p.trim().parse::<i32>())
        .collect::<Result<_, _>>()
        .map_err(|e| format!("{e} in {text:?}"))?;
    match parts[..] {
        [x, y, z] => Ok(Origin::At([x, y, z])),
        [x, z] => Ok(Origin::At([x, 64, z])),
        _ => Err(format!("expected x,y,z, x,z or player, got {text:?}")),
    }
}

fn main() -> ExitCode {
    match run(Cli::parse()) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: {e:#}");
            ExitCode::FAILURE
        }
    }
}

fn open(common: &Common) -> Result<World> {
    let dir = match (&common.bundle, &common.game_version) {
        (Some(dir), _) => dir.clone(),
        (None, Some(version)) => common.bundles.join(version),
        (None, None) => {
            let found = spyglass::bundles_in(&common.bundles).with_context(|| {
                format!(
                    "no bundles in {}; extract one with spyglass-extract",
                    common.bundles.display()
                )
            })?;
            match found.into_iter().next() {
                Some(b) => b.dir,
                None => bail!(
                    "no bundles in {}; extract one with spyglass-extract",
                    common.bundles.display()
                ),
            }
        }
    };
    World::open(&dir).with_context(|| format!("loading the bundle in {}", dir.display()))
}

/// What every answer is printed with.
struct Out<'a> {
    session: &'a Session<'a>,
    json: bool,
    /// The save, with `--world`.
    report: Option<&'a SaveReport>,
}

impl Out<'_> {
    /// Resolves `--from`.
    fn origin(&self, from: Origin) -> Result<[i32; 3]> {
        match from {
            Origin::At(at) => Ok(at),
            Origin::Player => {
                let Some(report) = self.report else {
                    bail!("--from player needs --world");
                };
                let Some(player) = &report.save.player else {
                    bail!(
                        "{} has no single player (a server world?)",
                        report.save.name
                    );
                };
                if player.dimension != "minecraft:overworld" {
                    bail!(
                        "the player is in {}; spyglass answers for the overworld only",
                        player.dimension
                    );
                }
                Ok(player.block())
            }
        }
    }
}

fn warnings_json(report: &SaveReport) -> Value {
    report
        .warnings
        .iter()
        .map(|w| json!({"kind": w.kind(), "message": w.to_string()}))
        .collect()
}

/// The fields every JSON answer starts with.
fn header(out: &Out<'_>, command: &str) -> serde_json::Map<String, Value> {
    let session = out.session;
    let world = session.world();
    let mut map = serde_json::Map::new();
    map.insert("format".into(), json!(JSON_FORMAT));
    map.insert("command".into(), json!(command));
    map.insert("version".into(), json!(world.version()));
    map.insert("dimension".into(), json!(world.dimension()));
    map.insert("seed".into(), json!(session.seed()));
    if let Some(report) = out.report {
        map.insert(
            "world".into(),
            json!({"name": report.save.name, "dir": path_json(&report.save.dir)}),
        );
        map.insert("warnings".into(), warnings_json(report));
    }
    map
}

/// A path as a JSON string. Text that isn't valid Unicode is replaced (cli-json.md).
fn path_json(path: &Path) -> Value {
    Value::String(path.to_string_lossy().into_owned())
}

fn print_json(mut map: serde_json::Map<String, Value>, fields: Value) -> Result<()> {
    match fields {
        Value::Object(fields) => map.extend(fields),
        other => bail!("internal error: JSON fields must be an object, not {other}"),
    }
    println!("{}", serde_json::to_string_pretty(&Value::Object(map))?);
    Ok(())
}

fn context(out: &Out<'_>, from: Option<[i32; 3]>) -> String {
    let session = out.session;
    let at = from.map_or(String::new(), |[x, y, z]| format!(" from {x} {y} {z}"));
    let world = out
        .report
        .map_or(String::new(), |r| format!("{}, ", r.save.name));
    format!(
        "{at} ({world}seed {}, Minecraft {})",
        session.seed(),
        session.world().version()
    )
}

fn run(cli: Cli) -> Result<()> {
    let what = match cli.command {
        Command::Locate { what } => what,
        Command::World { what } => return world(what),
    };
    let common = match &what {
        Locate::Structure { common, .. }
        | Locate::Biome { common, .. }
        | Locate::Slime { common, .. }
        | Locate::Spawn { common } => common,
    };
    let (world, seed, report) = match (&common.world, &common.seed) {
        (Some(save), _) => {
            let dir = spyglass::find_save(save)?;
            let report = spyglass::inspect_save(&dir, &common.bundles, Scan::Quick)?;
            let world = report.open_world()?;
            let seed = report.save.seed;
            (world, seed, Some(report))
        }
        (None, Some(seed)) => (open(common)?, spyglass::parse_seed(seed)?, None),
        (None, None) => bail!("give --seed or --world"),
    };
    let session = world.session(seed)?;
    let out = Out {
        session: &session,
        json: common.json,
        report: report.as_ref(),
    };
    match &what {
        Locate::Structure {
            target,
            from,
            radius,
            ..
        } => structure(&out, target, out.origin(from.from)?, *radius)?,
        Locate::Biome {
            biome,
            from,
            radius,
            ..
        } => self::biome(&out, biome, out.origin(from.from)?, *radius)?,
        Locate::Slime { from, radius, .. } => slime(&out, out.origin(from.from)?, *radius)?,
        Locate::Spawn { .. } => spawn(&out)?,
    }
    if let (false, Some(report)) = (out.json, &report) {
        for warning in &report.warnings {
            println!("warning: {warning}");
        }
    }
    Ok(())
}

fn structure(out: &Out<'_>, target: &str, from: [i32; 3], radius: i32) -> Result<()> {
    let (session, as_json) = (out.session, out.json);
    let found = session.locate_structure(target, from, radius)?;
    if as_json {
        let hits: Vec<Value> = found
            .hits
            .iter()
            .map(|h| {
                json!({
                    "position": {"x": h.start.position[0], "z": h.start.position[2]},
                    "chunk": h.start.chunk,
                    "set": h.start.set,
                    "structures": h.start.structures,
                    "certain": h.start.certain,
                    "blocks_away": h.blocks_away,
                })
            })
            .collect();
        return print_json(
            header(out, "locate structure"),
            json!({
                "target": target,
                "from": from,
                "radius": radius,
                "complete": found.complete,
                "certain_answer": found.certain_answer,
                "hits": hits,
            }),
        );
    }
    println!("{target}{}", context(out, Some(from)));
    if found.hits.is_empty() {
        println!("  none within {radius} rings");
        return Ok(());
    }
    for h in found.hits.iter().take(SHOWN) {
        let [x, _, z] = h.start.position;
        println!(
            "  {:>9} ~ {:<9} {:>7} blocks  {:<10} {}",
            x,
            z,
            h.blocks_away,
            if h.start.certain {
                "certain"
            } else {
                "candidate"
            },
            h.start.structures.join(" or "),
        );
    }
    if found.hits.len() > SHOWN {
        println!(
            "  ... and {} more (--json lists all)",
            found.hits.len() - SHOWN
        );
    }
    if found.hits.iter().any(|h| !h.start.certain) {
        let rest = if found.complete && found.certain_answer.is_some() {
            "."
        } else {
            ", or further out."
        };
        println!(
            "Candidates depend on terrain (or a tied biome), which spyglass doesn't compute yet. \
             The game's answer is the first of these it generates, usually the first listed{rest}"
        );
    }
    Ok(())
}

fn biome(out: &Out<'_>, biome: &str, from: [i32; 3], radius: i32) -> Result<()> {
    let (session, as_json) = (out.session, out.json);
    let found = session.locate_biome(biome, from, radius)?;
    if as_json {
        let hits: Vec<Value> = found
            .hits
            .iter()
            .map(|h| {
                json!({
                    "position": {"x": h.position[0], "y": h.position[1], "z": h.position[2]},
                    "biome": h.biome.biome,
                    "tied": h.biome.tied,
                    "certain": h.certain,
                    "blocks_away": h.blocks_away,
                })
            })
            .collect();
        return print_json(
            header(out, "locate biome"),
            json!({"target": biome, "from": from, "radius": radius, "hits": hits}),
        );
    }
    println!("{biome}{}", context(out, Some(from)));
    if found.hits.is_empty() {
        println!("  none within {radius} blocks");
        return Ok(());
    }
    for h in found.hits.iter().take(SHOWN) {
        let [x, y, z] = h.position;
        let tie = if h.biome.tied.is_empty() {
            String::new()
        } else {
            format!(" (tied: {})", h.biome.tied.join(", "))
        };
        println!(
            "  {x:>9} {y:>4} {z:<9} {:>7} blocks  {}{tie}",
            h.blocks_away,
            if h.certain { "certain" } else { "candidate" },
        );
    }
    if found.hits.iter().any(|h| !h.certain) {
        println!(
            "Candidates are tied cells, where the game's biome depends on lookup history; the \
             game's answer is the first of these where it finds the biome."
        );
    }
    Ok(())
}

fn slime(out: &Out<'_>, from: [i32; 3], radius: i32) -> Result<()> {
    let (session, as_json) = (out.session, out.json);
    let centre = [from[0] >> 4, from[2] >> 4];
    let min = [
        centre[0].saturating_sub(radius),
        centre[1].saturating_sub(radius),
    ];
    let max = [
        centre[0].saturating_add(radius),
        centre[1].saturating_add(radius),
    ];
    let mut chunks = session.slime_chunks(min, max);
    let distance = |[x, z]: [i32; 2]| {
        let (dx, dz) = (
            i64::from(x) - i64::from(centre[0]),
            i64::from(z) - i64::from(centre[1]),
        );
        dx * dx + dz * dz
    };
    chunks.sort_by_key(|&c| (distance(c), c[1], c[0]));
    if as_json {
        return print_json(
            header(out, "locate slime"),
            json!({"from": from, "radius": radius, "chunks": chunks}),
        );
    }
    println!(
        "Slime chunks within {radius} chunks of chunk {} {}{}",
        centre[0],
        centre[1],
        context(out, None)
    );
    for &[x, z] in chunks.iter().take(SHOWN * 2) {
        println!(
            "  chunk {x:>6} {z:<6}  blocks {}..{}, {}..{}",
            x << 4,
            (x << 4) + 15,
            z << 4,
            (z << 4) + 15
        );
    }
    if chunks.len() > SHOWN * 2 {
        println!(
            "  ... and {} more (--json lists all)",
            chunks.len() - SHOWN * 2
        );
    }
    Ok(())
}

fn spawn(out: &Out<'_>) -> Result<()> {
    let (session, as_json) = (out.session, out.json);
    let origin = session.spawn_origin();
    if as_json {
        return print_json(
            header(out, "locate spawn"),
            json!({
                "chunk": origin.chunk,
                "position": origin.position.map(|[x, _, z]| json!({"x": x, "z": z})),
                "platform_dependent": origin.platform_dependent,
            }),
        );
    }
    let [cx, cz] = origin.chunk;
    println!("World spawn{}", context(out, None));
    println!(
        "  the spawn search starts in chunk {cx} {cz} (blocks {}..{}, {}..{})",
        cx << 4,
        (cx << 4) + 15,
        cz << 4,
        (cz << 4) + 15
    );
    if let Some([x, _, z]) = origin.position {
        println!("  the climate search's best point is {x} ~ {z}");
    }
    if origin.platform_dependent {
        println!("  this may differ on other platforms (Java's sin and cos aren't exact)");
    }
    println!(
        "The spawn itself is in the 11 x 11 chunks around it, chosen by terrain, which spyglass \
         doesn't compute yet."
    );
    Ok(())
}

fn world(what: WorldCmd) -> Result<()> {
    match what {
        WorldCmd::List { bundles, json } => world_list(&bundles, json),
        WorldCmd::Info {
            save,
            bundles,
            quick,
            json,
        } => {
            let dir = spyglass::find_save(&save)?;
            let scan = if quick { Scan::Quick } else { Scan::Chunks };
            let report = spyglass::inspect_save(&dir, &bundles, scan)?;
            world_info(&report, json)
        }
    }
}

/// A save's summary for JSON: what it says, and what spyglass makes of it.
fn save_json(report: &SaveReport) -> Value {
    let save = &report.save;
    let location =
        |l: &spyglass::SaveLocation| json!({"dimension": l.dimension, "position": l.pos});
    json!({
        "name": save.name,
        "dir": path_json(&save.dir),
        "data_version": save.data_version,
        "version_name": save.version_name,
        "seed": save.seed,
        "generate_structures": save.generate_structures,
        "data_packs": save.enabled_packs,
        "spawn": save.spawn.as_ref().map(location),
        "player": save.player.as_ref().map(location),
        "bundle": report.bundle.as_ref().map(|b| path_json(&b.dir)),
        "answerable": report.answerable(),
        "warnings": warnings_json(report),
    })
}

fn world_list(bundles: &std::path::Path, as_json: bool) -> Result<()> {
    let mut rows = Vec::new();
    for found in spyglass::launcher_saves() {
        let report = spyglass::inspect_save(&found.dir, bundles, Scan::Quick);
        rows.push((found, report));
    }
    if as_json {
        let saves: Vec<Value> = rows
            .iter()
            .map(|(found, report)| match report {
                Ok(r) => {
                    let mut v = save_json(r);
                    v["launcher"] = json!(found.launcher);
                    v
                }
                Err(e) => {
                    json!({"launcher": found.launcher, "dir": path_json(&found.dir), "error": e.to_string()})
                }
            })
            .collect();
        println!(
            "{}",
            serde_json::to_string_pretty(&json!({
                "format": JSON_FORMAT,
                "command": "world list",
                "saves": saves,
            }))?
        );
        return Ok(());
    }
    if rows.is_empty() {
        println!("no saves found in the official launcher's or the Modrinth App's folders");
        return Ok(());
    }
    let mut launcher = "";
    for (found, report) in &rows {
        if found.launcher != launcher {
            launcher = &found.launcher;
            println!("{launcher}");
        }
        let folder = found.dir.file_name().unwrap_or_default().to_string_lossy();
        match report {
            Ok(r) => println!(
                "  {:<32} {:<9} {}",
                folder,
                r.save.version_name.as_deref().unwrap_or("?"),
                if r.answerable() {
                    "supported".to_string()
                } else {
                    r.warnings
                        .iter()
                        .find(|w| w.blocks_answers())
                        .map_or_else(String::new, |w| format!("unsupported: {w}"))
                }
            ),
            Err(e) => println!("  {folder:<32} unreadable: {e}"),
        }
    }
    Ok(())
}

fn world_info(report: &SaveReport, as_json: bool) -> Result<()> {
    if as_json {
        let mut v = save_json(report);
        v["format"] = json!(JSON_FORMAT);
        v["command"] = json!("world info");
        println!("{}", serde_json::to_string_pretty(&v)?);
        return Ok(());
    }
    let save = &report.save;
    let place = |l: &spyglass::SaveLocation| {
        let [x, y, z] = l.block();
        format!("{x} {y} {z} in {}", l.dimension)
    };
    println!("{} ({})", save.name, save.dir.display());
    println!(
        "  version  {} (data version {})",
        save.version_name.as_deref().unwrap_or("unknown"),
        save.data_version
            .map_or("none, before 1.9".to_string(), |v| v.to_string())
    );
    println!("  seed     {}", save.seed);
    if let Some(spawn) = &save.spawn {
        println!("  spawn    {}", place(spawn));
    }
    if let Some(player) = &save.player {
        println!("  player   {}", place(player));
    }
    println!("  packs    {}", save.enabled_packs.join(", "));
    match &report.bundle {
        Some(b) => println!("  bundle   {}", b.dir.display()),
        None => println!("  bundle   none"),
    }
    if report.warnings.is_empty() {
        println!("spyglass's answers for this world are exact where they say so.");
    }
    for warning in &report.warnings {
        let level = if warning.blocks_answers() {
            "error"
        } else {
            "warning"
        };
        println!("{level}: {warning}");
    }
    Ok(())
}
