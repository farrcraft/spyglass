#[test]
fn every_case_is_correctly_rounded() {
    let mut wrong = Vec::new();
    for &(function, x, y, expected) in CASES {
        let (x, y) = (f64::from_bits(x), f64::from_bits(y));
        let ours = match function {
            "sin" => spyglass_math::sin(x),
            "cos" => spyglass_math::cos(x),
            "log" => spyglass_math::log(x),
            _ => spyglass_math::pow(x, y),
        };
        if ours.to_bits() != expected {
            wrong.push(format!(
                "{function}({x:e}, {y:e}) = {ours:e}, not {:e}",
                f64::from_bits(expected)
            ));
        }
    }
    assert!(
        wrong.is_empty(),
        "{} of {} wrong:
{}",
        wrong.len(),
        CASES.len(),
        wrong.join(
            "
"
        )
    );
}
