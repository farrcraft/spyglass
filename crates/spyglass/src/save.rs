//! World saves through the public API: reading a save, matching it to a bundle, and saying what
//! makes it unpredictable. See `docs/specs/world-saves.md`.

use std::collections::HashMap;
use std::fmt;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex};

use serde_json::Value;
use spyglass_data::bundle::Bundle;
use spyglass_world::{PackContents, region};

use crate::{BundleInfo, Dimension, Error, Game, PRESET, Result, World, bundles_in};

/// A position in a dimension, from a save.
#[derive(Debug, Clone, PartialEq)]
pub struct SaveLocation {
    /// The dimension, e.g. `minecraft:overworld`.
    pub dimension: String,
    /// The position, in blocks.
    pub pos: [f64; 3],
}

impl SaveLocation {
    /// The dimension, if it's one of the Default preset's.
    pub fn dimension_kind(&self) -> Option<Dimension> {
        Dimension::from_id(&self.dimension)
    }

    /// The block containing the position.
    pub fn block(&self) -> [i32; 3] {
        self.pos.map(|v| v.floor() as i32)
    }
}

/// What a world save says about itself.
#[derive(Debug, Clone, PartialEq)]
pub struct SaveInfo {
    /// The save's directory.
    pub dir: PathBuf,
    /// The name shown in the world list.
    pub name: String,
    /// The data version it was last saved in; `None` before 1.9.
    pub data_version: Option<i32>,
    /// The game version name, e.g. `26.3`, if recorded.
    pub version_name: Option<String>,
    /// The world seed.
    pub seed: i64,
    /// Whether structures generate.
    pub generate_structures: bool,
    /// Enabled data packs, in load order.
    pub enabled_packs: Vec<String>,
    /// The world spawn.
    pub spawn: Option<SaveLocation>,
    /// The single player, in single-player saves.
    pub player: Option<SaveLocation>,
}

/// Why a data pack may change worldgen.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PackConcern {
    /// It has worldgen files.
    Worldgen {
        /// How many.
        files: usize,
    },
    /// A built-in feature pack or a mod's pack, whose files aren't in the save.
    Uninspectable,
    /// Its zip or folder is missing.
    Missing,
}

/// Something that makes spyglass's answers for a save inexact, or impossible.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SaveWarning {
    /// No bundle has the save's data version. Blocks answers.
    NoBundle {
        /// The save's data version.
        data_version: Option<i32>,
        /// Its version name, to extract.
        version_name: Option<String>,
    },
    /// A dimension's generator isn't the Default preset's. Blocks answers in that dimension.
    UnsupportedGenerator {
        /// The dimension.
        dimension: Dimension,
        /// The bundled preset it matches, e.g. `minecraft:large_biomes`, if any.
        preset: Option<String>,
        /// The generator's type, and for noise generators their settings, e.g.
        /// `minecraft:flat` or `minecraft:noise (minecraft:amplified)`.
        generator: String,
    },
    /// The save doesn't generate structures: structure answers don't exist in it.
    StructuresDisabled,
    /// A data pack that may change worldgen.
    DataPack {
        /// The pack, e.g. `file/terralith.zip`.
        name: String,
        /// Why.
        concern: PackConcern,
    },
    /// A modded game has opened the world; mods can change worldgen without data packs.
    Modded,
    /// Chunks generated by older versions: their terrain and structures follow that version.
    OlderChunks {
        /// The dimension whose region files have them.
        dimension: Dimension,
        /// Chunks older than the save's data version.
        older: usize,
        /// Chunks in the dimension's region files.
        total: usize,
    },
    /// Region files that couldn't be opened or read, so their chunks weren't counted for
    /// [`OlderChunks`](Self::OlderChunks).
    UnreadableRegions {
        /// The dimension whose region files they are.
        dimension: Dimension,
        /// How many.
        files: usize,
    },
}

impl SaveWarning {
    /// Whether spyglass refuses to answer: in [`dimension`](Self::dimension), or in the whole
    /// save if the warning has none.
    pub fn blocks_answers(&self) -> bool {
        matches!(
            self,
            SaveWarning::NoBundle { .. } | SaveWarning::UnsupportedGenerator { .. }
        )
    }

    /// The dimension the warning is about, or `None` if it's about the whole save.
    pub fn dimension(&self) -> Option<Dimension> {
        match self {
            SaveWarning::UnsupportedGenerator { dimension, .. }
            | SaveWarning::OlderChunks { dimension, .. }
            | SaveWarning::UnreadableRegions { dimension, .. } => Some(*dimension),
            _ => None,
        }
    }

    /// Whether spyglass refuses to answer in `dimension` because of this warning.
    pub fn blocks(&self, dimension: Dimension) -> bool {
        self.blocks_answers() && self.dimension().is_none_or(|d| d == dimension)
    }

    /// A short machine-readable kind, e.g. `no_bundle`.
    pub fn kind(&self) -> &'static str {
        match self {
            SaveWarning::NoBundle { .. } => "no_bundle",
            SaveWarning::UnsupportedGenerator { .. } => "unsupported_generator",
            SaveWarning::StructuresDisabled => "structures_disabled",
            SaveWarning::DataPack { .. } => "data_pack",
            SaveWarning::Modded => "modded",
            SaveWarning::OlderChunks { .. } => "older_chunks",
            SaveWarning::UnreadableRegions { .. } => "unreadable_regions",
        }
    }
}

impl fmt::Display for SaveWarning {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            SaveWarning::NoBundle {
                data_version,
                version_name,
            } => {
                let version = version_name.as_deref().unwrap_or("its version");
                match data_version {
                    Some(v) => write!(
                        f,
                        "no bundle for data version {v}; extract one for {version} with spyglass-extract"
                    ),
                    None => write!(
                        f,
                        "the save is from before 1.9, which spyglass can't predict"
                    ),
                }
            }
            SaveWarning::UnsupportedGenerator {
                dimension,
                preset,
                generator,
            } => {
                let name = dimension.name();
                match preset {
                    Some(p) => write!(
                        f,
                        "{name} uses the {p} preset ({generator}); spyglass supports only the Default preset"
                    ),
                    None => write!(
                        f,
                        "{name} uses a custom generator ({generator}); spyglass supports only the Default preset"
                    ),
                }
            }
            SaveWarning::StructuresDisabled => write!(f, "structures are turned off in this world"),
            SaveWarning::DataPack { name, concern } => match concern {
                PackConcern::Worldgen { files } => {
                    write!(
                        f,
                        "data pack {name} has {files} worldgen files and may change generation"
                    )
                }
                PackConcern::Uninspectable => write!(
                    f,
                    "data pack {name} is built in or from a mod, so spyglass can't check whether it changes generation"
                ),
                PackConcern::Missing => {
                    write!(f, "data pack {name} is enabled but missing from datapacks/")
                }
            },
            SaveWarning::Modded => write!(
                f,
                "the world has been opened with a modded game; mods can change generation"
            ),
            SaveWarning::OlderChunks {
                dimension,
                older,
                total,
            } => write!(
                f,
                "{older} of {total} chunks in {} were generated by older versions and follow their rules",
                dimension.name()
            ),
            SaveWarning::UnreadableRegions { dimension, files } => write!(
                f,
                "{files} region files in {} couldn't be read, so their chunks weren't checked",
                dimension.name()
            ),
        }
    }
}

/// A save and what spyglass makes of it.
#[derive(Debug, Clone, PartialEq)]
pub struct SaveReport {
    /// What the save says.
    pub save: SaveInfo,
    /// The bundle with the save's data version, if there is one.
    pub bundle: Option<BundleInfo>,
    /// Everything that makes answers inexact or impossible, most serious first.
    pub warnings: Vec<SaveWarning>,
}

impl SaveReport {
    /// Whether spyglass can answer for the save in every dimension: no warning blocks answers.
    pub fn answerable(&self) -> bool {
        !self.warnings.iter().any(SaveWarning::blocks_answers)
    }

    /// Whether spyglass can answer for the save in `dimension`.
    pub fn answerable_in(&self, dimension: Dimension) -> bool {
        !self.warnings.iter().any(|w| w.blocks(dimension))
    }

    /// What blocks answers in `dimension`, joined; `None` if nothing does.
    fn blocking(&self, dimension: Dimension) -> Option<String> {
        let reasons: Vec<String> = self
            .warnings
            .iter()
            .filter(|w| w.blocks(dimension))
            .map(ToString::to_string)
            .collect();
        (!reasons.is_empty()).then(|| reasons.join("; "))
    }

    /// The save's `dimension` as a [`World`], or an error listing what blocks it.
    pub fn open_world(&self, dimension: Dimension) -> Result<World> {
        match (&self.bundle, self.blocking(dimension)) {
            (Some(bundle), None) => World::open_dimension(&bundle.dir, dimension),
            (_, reasons) => Err(Error::Unsupported(reasons.unwrap_or_default())),
        }
    }

    /// The save's bundle as a [`Game`], whose [`world`](Game::world) refuses each dimension
    /// that something blocks, listing what. An error if no bundle has the save's version.
    pub fn open_game(&self) -> Result<Game> {
        match &self.bundle {
            Some(bundle) => {
                Game::open_blocked(&bundle.dir, Dimension::ALL.map(|d| self.blocking(d)))
            }
            None => Err(Error::Unsupported(
                self.blocking(Dimension::Overworld).unwrap_or_default(),
            )),
        }
    }
}

/// A save found in a launcher's saves folder.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LauncherSave {
    /// Which launcher, e.g. `Minecraft Launcher` or `Modrinth (Fabric 26.3)`.
    pub launcher: String,
    /// The save's folder.
    pub dir: PathBuf,
}

/// Every save in the known launchers' default saves folders: the official launcher's and each
/// Modrinth App profile's.
pub fn launcher_saves() -> Vec<LauncherSave> {
    spyglass_world::launchers::saves_dirs()
        .into_iter()
        .flat_map(|saves| {
            spyglass_world::launchers::saves_in(&saves.dir)
                .into_iter()
                .map(move |dir| LauncherSave {
                    launcher: saves.launcher.clone(),
                    dir,
                })
        })
        .collect()
}

/// A save by path, or else by folder name among [`launcher_saves`] if exactly one matches.
pub fn find_save(path_or_name: &str) -> Result<PathBuf> {
    let path = PathBuf::from(path_or_name);
    if spyglass_world::Save::is_save(&path) {
        return Ok(path);
    }
    let matches: Vec<LauncherSave> = launcher_saves()
        .into_iter()
        .filter(|s| s.dir.file_name().is_some_and(|n| n == path_or_name))
        .collect();
    match matches.as_slice() {
        [one] => Ok(one.dir.clone()),
        [] => Err(Error::Unknown {
            what: "world save",
            id: path_or_name.to_string(),
        }),
        many => Err(Error::AmbiguousSave {
            name: path_or_name.to_string(),
            matches: many.iter().map(|s| s.dir.clone()).collect(),
        }),
    }
}

/// How thoroughly [`inspect_save`] looks.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Scan {
    /// Also count chunks generated by older versions, from each dimension's region files.
    /// Takes about a second per 30,000 chunks.
    Chunks,
    /// Only the save's own files.
    Quick,
}

/// Reads the save in `dir` and assesses it against the bundles in `bundles` (e.g. `bundles/`).
/// To assess several saves, a [`SaveInspector`] reads each bundle once.
pub fn inspect_save(
    dir: impl AsRef<Path>,
    bundles: impl AsRef<Path>,
    scan: Scan,
) -> Result<SaveReport> {
    SaveInspector::new(bundles)?.inspect(dir, scan)
}

/// A bundle's world presets: each id and its generator for each of [`Dimension::ALL`] it has,
/// normalized.
type Presets = Vec<(String, [Option<Value>; 3])>;

/// Assesses saves against one bundles folder. Each bundle's world presets are read once, the
/// first time a save needs them.
pub struct SaveInspector {
    bundles: Vec<BundleInfo>,
    /// Each bundle's generators by preset id, normalized, by bundle folder.
    presets: Mutex<HashMap<PathBuf, Arc<Presets>>>,
}

impl SaveInspector {
    /// An inspector for the bundles in `bundles` (e.g. `bundles/`). A missing folder has none,
    /// so every save gets [`SaveWarning::NoBundle`].
    pub fn new(bundles: impl AsRef<Path>) -> Result<Self> {
        Ok(SaveInspector {
            bundles: bundles_in(bundles)?,
            presets: Mutex::new(HashMap::new()),
        })
    }

    /// The generators of `bundle`'s world presets.
    fn presets(&self, bundle: &BundleInfo) -> Result<Arc<Presets>> {
        let mut cache = self.presets.lock().unwrap_or_else(|e| e.into_inner());
        if let Some(p) = cache.get(&bundle.dir) {
            return Ok(p.clone());
        }
        let opened = Bundle::open(&bundle.dir)?;
        let mut presets = Vec::new();
        for id in opened.registry_ids("worldgen/world_preset") {
            let preset = opened.resource("worldgen/world_preset", &id)?;
            let generators = Dimension::ALL.map(|d| {
                preset
                    .get("dimensions")
                    .and_then(|ds| ds.get(d.id()))
                    .and_then(|d| d.get("generator"))
                    .map(normalize)
            });
            presets.push((id, generators));
        }
        let presets = Arc::new(presets);
        cache.insert(bundle.dir.clone(), presets.clone());
        Ok(presets)
    }

    /// Reads the save in `dir` and assesses it.
    pub fn inspect(&self, dir: impl AsRef<Path>, scan: Scan) -> Result<SaveReport> {
        inspect(self, dir.as_ref(), scan)
    }
}

fn inspect(inspector: &SaveInspector, dir: &Path, scan: Scan) -> Result<SaveReport> {
    let save = spyglass_world::Save::read(dir)?;
    let bundle = match save.data_version {
        Some(v) => inspector
            .bundles
            .iter()
            .find(|b| i64::from(b.data_version) == i64::from(v))
            .cloned(),
        None => None,
    };
    let mut warnings = Vec::new();
    if bundle.is_none() {
        warnings.push(SaveWarning::NoBundle {
            data_version: save.data_version,
            version_name: save.version_name.clone(),
        });
    }
    // Without a bundle there are no presets to compare with; the missing bundle already blocks
    // answers.
    if let Some(bundle) = &bundle {
        let presets = inspector.presets(bundle)?;
        warnings.extend(generator_warnings(&save, &presets));
    }
    if !save.generate_structures {
        warnings.push(SaveWarning::StructuresDisabled);
    }
    for (name, contents) in save.packs() {
        let concern = match contents {
            PackContents::Vanilla
            | PackContents::Files {
                worldgen_files: 0, ..
            } => continue,
            PackContents::Files { worldgen_files, .. } => PackConcern::Worldgen {
                files: worldgen_files,
            },
            PackContents::Uninspectable => PackConcern::Uninspectable,
            PackContents::Missing { .. } => PackConcern::Missing,
        };
        warnings.push(SaveWarning::DataPack { name, concern });
    }
    if save.was_modded {
        warnings.push(SaveWarning::Modded);
    }
    if scan == Scan::Chunks {
        for dimension in Dimension::ALL {
            let dir = save.region_dir(dimension.id())?;
            let chunks = region::chunk_versions(&dir).map_err(|source| Error::Io {
                path: dir.clone(),
                source,
            })?;
            let older = chunks.older_than(save.data_version.unwrap_or(i32::MAX));
            if older > 0 {
                warnings.push(SaveWarning::OlderChunks {
                    dimension,
                    older,
                    total: chunks.total(),
                });
            }
            if chunks.unreadable_files > 0 {
                warnings.push(SaveWarning::UnreadableRegions {
                    dimension,
                    files: chunks.unreadable_files,
                });
            }
        }
    }
    let location = |l: &spyglass_world::Location| SaveLocation {
        dimension: l.dimension.clone(),
        pos: l.pos,
    };
    Ok(SaveReport {
        save: SaveInfo {
            dir: save.dir.clone(),
            name: save.name.clone(),
            data_version: save.data_version,
            version_name: save.version_name.clone(),
            seed: save.seed,
            generate_structures: save.generate_structures,
            enabled_packs: save.enabled_packs.clone(),
            spawn: save.spawn.as_ref().map(location),
            player: save.player.as_ref().map(location),
        },
        bundle,
        warnings,
    })
}

/// A JSON value with ids namespaced and booleans as 0 or 1, so a save's NBT and a bundle's JSON
/// compare equal when the game would read them the same.
fn normalize(value: &Value) -> Value {
    match value {
        Value::Bool(b) => normalize(&Value::from(u8::from(*b))),
        Value::Number(n) => n
            .as_f64()
            .and_then(serde_json::Number::from_f64)
            .map_or(Value::Null, Value::Number),
        Value::String(s)
            if !s.contains(':')
                && !s.is_empty()
                && s.bytes().all(|b| {
                    b.is_ascii_lowercase() || b.is_ascii_digit() || b"_-./".contains(&b)
                }) =>
        {
            Value::from(format!("minecraft:{s}"))
        }
        Value::Array(items) => Value::Array(items.iter().map(normalize).collect()),
        Value::Object(map) => {
            Value::Object(map.iter().map(|(k, v)| (k.clone(), normalize(v))).collect())
        }
        other => other.clone(),
    }
}

/// A warning for each of the Default preset's dimensions whose generator in the save isn't the
/// preset's. `presets` are the bundle's, as [`SaveInspector::presets`] gives them. A dimension
/// the bundle's Default preset doesn't have isn't checked, since no world opens for it.
fn generator_warnings(save: &spyglass_world::Save, presets: &Presets) -> Vec<SaveWarning> {
    let Some((_, supported)) = presets.iter().find(|(id, _)| id == PRESET) else {
        return Vec::new();
    };
    let mut warnings = Vec::new();
    for dimension in Dimension::ALL {
        let i = dimension.index();
        let Some(expected) = &supported[i] else {
            continue;
        };
        let Some(generator) = save.generators.get(dimension.id()) else {
            warnings.push(SaveWarning::UnsupportedGenerator {
                dimension,
                preset: None,
                generator: "none".into(),
            });
            continue;
        };
        let ours = normalize(generator);
        if ours == *expected {
            continue;
        }
        // Other presets share some dimensions' generators with the Default one (every preset
        // has the same Nether), so the Default preset is compared first, and the others only to
        // name a mismatch.
        let preset = presets
            .iter()
            .find(|(_, theirs)| theirs[i].as_ref() == Some(&ours))
            .map(|(id, _)| id.clone());
        warnings.push(SaveWarning::UnsupportedGenerator {
            dimension,
            preset,
            generator: describe(generator),
        });
    }
    warnings
}

/// A generator, briefly: `legacy <name>`, or its type and, for noise generators, its settings.
fn describe(generator: &Value) -> String {
    if let Some(legacy) = generator.get("legacy_generator") {
        let name = legacy
            .get("name")
            .and_then(Value::as_str)
            .unwrap_or("default");
        return format!("legacy {name}");
    }
    let kind = generator.get("type").and_then(Value::as_str).unwrap_or("?");
    match generator.get("settings").and_then(Value::as_str) {
        Some(settings) => format!("{kind} ({settings})"),
        None => kind.to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn normalized_values_compare_like_the_game() {
        assert_eq!(
            normalize(&json!({"settings": "overworld", "features": false, "height": 1})),
            normalize(&json!({"settings": "minecraft:overworld", "features": 0, "height": 1.0}))
        );
        assert_ne!(
            normalize(&json!({"settings": "minecraft:overworld"})),
            normalize(&json!({"settings": "minecraft:amplified"}))
        );
        // Text that isn't an id is left alone.
        assert_eq!(
            normalize(&json!("3;minecraft:bedrock")),
            json!("3;minecraft:bedrock")
        );
        assert_eq!(normalize(&json!("Seed Check")), json!("Seed Check"));
    }
}
