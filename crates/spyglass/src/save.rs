//! World saves through the public API: reading a save, matching it to a bundle, and saying what
//! makes it unpredictable. See `docs/specs/world-saves.md`.

use std::fmt;
use std::path::{Path, PathBuf};

use serde_json::Value;
use spyglass_data::bundle::Bundle;
use spyglass_world::{PackContents, region};

use crate::{BundleInfo, Error, Result, World, bundles_in};

/// The overworld, the only dimension spyglass answers for so far.
const OVERWORLD: &str = "minecraft:overworld";
/// The world preset spyglass supports.
const SUPPORTED_PRESET: &str = "minecraft:normal";

/// A position in a dimension, from a save.
#[derive(Debug, Clone, PartialEq)]
pub struct SaveLocation {
    /// The dimension, e.g. `minecraft:overworld`.
    pub dimension: String,
    /// The position, in blocks.
    pub pos: [f64; 3],
}

impl SaveLocation {
    /// The block containing the position.
    pub fn block(&self) -> [i32; 3] {
        self.pos.map(|v| v.floor() as i32)
    }
}

/// What a world save says about itself.
#[derive(Debug, Clone, PartialEq)]
pub struct SaveInfo {
    /// The save's directory.
    pub dir: PathBuf,
    /// The name shown in the world list.
    pub name: String,
    /// The data version it was last saved in; `None` before 1.9.
    pub data_version: Option<i32>,
    /// The game version name, e.g. `26.3`, if recorded.
    pub version_name: Option<String>,
    /// The world seed.
    pub seed: i64,
    /// Whether structures generate.
    pub generate_structures: bool,
    /// Enabled data packs, in load order.
    pub enabled_packs: Vec<String>,
    /// The world spawn.
    pub spawn: Option<SaveLocation>,
    /// The single player, in single-player saves.
    pub player: Option<SaveLocation>,
}

/// Why a data pack may change worldgen.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PackConcern {
    /// It has worldgen files.
    Worldgen {
        /// How many.
        files: usize,
    },
    /// A built-in feature pack or a mod's pack, whose files aren't in the save.
    Uninspectable,
    /// Its zip or folder is missing.
    Missing,
}

/// Something that makes spyglass's answers for a save inexact, or impossible.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SaveWarning {
    /// No bundle has the save's data version. Blocks answers.
    NoBundle {
        /// The save's data version.
        data_version: Option<i32>,
        /// Its version name, to extract.
        version_name: Option<String>,
    },
    /// The overworld's generator isn't the Default preset's. Blocks answers.
    UnsupportedGenerator {
        /// The bundled preset it matches, e.g. `minecraft:large_biomes`, if any.
        preset: Option<String>,
        /// The generator's type, and for noise generators their settings, e.g.
        /// `minecraft:flat` or `minecraft:noise (minecraft:amplified)`.
        generator: String,
    },
    /// The save doesn't generate structures: structure answers don't exist in it.
    StructuresDisabled,
    /// A data pack that may change worldgen.
    DataPack {
        /// The pack, e.g. `file/terralith.zip`.
        name: String,
        /// Why.
        concern: PackConcern,
    },
    /// A modded game has opened the world; mods can change worldgen without data packs.
    Modded,
    /// Chunks generated by older versions: their terrain and structures follow that version.
    OlderChunks {
        /// Chunks older than the save's data version.
        older: usize,
        /// Chunks in the overworld's region files.
        total: usize,
    },
}

impl SaveWarning {
    /// Whether spyglass refuses to answer for the save.
    pub fn blocks_answers(&self) -> bool {
        matches!(
            self,
            SaveWarning::NoBundle { .. } | SaveWarning::UnsupportedGenerator { .. }
        )
    }

    /// A short machine-readable kind, e.g. `no_bundle`.
    pub fn kind(&self) -> &'static str {
        match self {
            SaveWarning::NoBundle { .. } => "no_bundle",
            SaveWarning::UnsupportedGenerator { .. } => "unsupported_generator",
            SaveWarning::StructuresDisabled => "structures_disabled",
            SaveWarning::DataPack { .. } => "data_pack",
            SaveWarning::Modded => "modded",
            SaveWarning::OlderChunks { .. } => "older_chunks",
        }
    }
}

impl fmt::Display for SaveWarning {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            SaveWarning::NoBundle {
                data_version,
                version_name,
            } => {
                let version = version_name.as_deref().unwrap_or("its version");
                match data_version {
                    Some(v) => write!(
                        f,
                        "no bundle for data version {v}; extract one for {version} with spyglass-extract"
                    ),
                    None => write!(
                        f,
                        "the save is from before 1.9, which spyglass can't predict"
                    ),
                }
            }
            SaveWarning::UnsupportedGenerator { preset, generator } => match preset {
                Some(p) => write!(
                    f,
                    "the overworld uses the {p} preset ({generator}); spyglass supports only the Default preset"
                ),
                None => write!(
                    f,
                    "the overworld uses a custom generator ({generator}); spyglass supports only the Default preset"
                ),
            },
            SaveWarning::StructuresDisabled => write!(f, "structures are turned off in this world"),
            SaveWarning::DataPack { name, concern } => match concern {
                PackConcern::Worldgen { files } => {
                    write!(
                        f,
                        "data pack {name} has {files} worldgen files and may change generation"
                    )
                }
                PackConcern::Uninspectable => write!(
                    f,
                    "data pack {name} is built in or from a mod, so spyglass can't check whether it changes generation"
                ),
                PackConcern::Missing => {
                    write!(f, "data pack {name} is enabled but missing from datapacks/")
                }
            },
            SaveWarning::Modded => write!(
                f,
                "the world has been opened with a modded game; mods can change generation"
            ),
            SaveWarning::OlderChunks { older, total } => write!(
                f,
                "{older} of {total} overworld chunks were generated by older versions and follow their rules"
            ),
        }
    }
}

/// A save and what spyglass makes of it.
#[derive(Debug, Clone, PartialEq)]
pub struct SaveReport {
    /// What the save says.
    pub save: SaveInfo,
    /// The bundle with the save's data version, if there is one.
    pub bundle: Option<BundleInfo>,
    /// Everything that makes answers inexact or impossible, most serious first.
    pub warnings: Vec<SaveWarning>,
}

impl SaveReport {
    /// Whether spyglass can answer for the save at all.
    pub fn answerable(&self) -> bool {
        !self.warnings.iter().any(SaveWarning::blocks_answers)
    }

    /// The save's overworld as a [`World`], or an error listing what blocks it.
    pub fn open_world(&self) -> Result<World> {
        let blocking: Vec<String> = self
            .warnings
            .iter()
            .filter(|w| w.blocks_answers())
            .map(ToString::to_string)
            .collect();
        match (&self.bundle, blocking.is_empty()) {
            (Some(bundle), true) => World::open(&bundle.dir),
            _ => Err(Error::Unsupported(blocking.join("; "))),
        }
    }
}

/// A save found in a launcher's saves folder.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LauncherSave {
    /// Which launcher, e.g. `Minecraft Launcher` or `Modrinth (Fabric 26.3)`.
    pub launcher: String,
    /// The save's folder.
    pub dir: PathBuf,
}

/// Every save in the known launchers' default saves folders: the official launcher's and each
/// Modrinth App profile's.
pub fn launcher_saves() -> Vec<LauncherSave> {
    spyglass_world::launchers::saves_dirs()
        .into_iter()
        .flat_map(|saves| {
            spyglass_world::launchers::saves_in(&saves.dir)
                .into_iter()
                .map(move |dir| LauncherSave {
                    launcher: saves.launcher.clone(),
                    dir,
                })
        })
        .collect()
}

/// A save by path, or else by folder name among [`launcher_saves`] if exactly one matches.
pub fn find_save(path_or_name: &str) -> Result<PathBuf> {
    let path = PathBuf::from(path_or_name);
    if spyglass_world::Save::is_save(&path) {
        return Ok(path);
    }
    let matches: Vec<LauncherSave> = launcher_saves()
        .into_iter()
        .filter(|s| s.dir.file_name().is_some_and(|n| n == path_or_name))
        .collect();
    match matches.as_slice() {
        [one] => Ok(one.dir.clone()),
        [] => Err(Error::Unknown {
            what: "world save",
            id: path_or_name.to_string(),
        }),
        many => Err(Error::Unsupported(format!(
            "{} saves are called {path_or_name:?}; give a path: {}",
            many.len(),
            many.iter()
                .map(|s| s.dir.display().to_string())
                .collect::<Vec<_>>()
                .join(", ")
        ))),
    }
}

/// How thoroughly [`inspect_save`] looks.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Scan {
    /// Also count chunks generated by older versions, from the overworld's region files. Takes
    /// about a second per 30,000 chunks.
    Chunks,
    /// Only the save's own files.
    Quick,
}

/// Reads the save in `dir` and assesses it against the bundles in `bundles` (e.g. `bundles/`).
pub fn inspect_save(
    dir: impl AsRef<Path>,
    bundles: impl AsRef<Path>,
    scan: Scan,
) -> Result<SaveReport> {
    let save = spyglass_world::Save::read(dir.as_ref())?;
    let bundle = match save.data_version {
        Some(v) => bundles_in(bundles)
            .unwrap_or_default()
            .into_iter()
            .find(|b| i64::from(b.data_version) == i64::from(v)),
        None => None,
    };
    let mut warnings = Vec::new();
    if bundle.is_none() {
        warnings.push(SaveWarning::NoBundle {
            data_version: save.data_version,
            version_name: save.version_name.clone(),
        });
    }
    if let Some(w) = generator_warning(&save, bundle.as_ref())? {
        warnings.push(w);
    }
    if !save.generate_structures {
        warnings.push(SaveWarning::StructuresDisabled);
    }
    for (name, contents) in save.packs() {
        let concern = match contents {
            PackContents::Vanilla
            | PackContents::Files {
                worldgen_files: 0, ..
            } => continue,
            PackContents::Files { worldgen_files, .. } => PackConcern::Worldgen {
                files: worldgen_files,
            },
            PackContents::Uninspectable => PackConcern::Uninspectable,
            PackContents::Missing { .. } => PackConcern::Missing,
        };
        warnings.push(SaveWarning::DataPack { name, concern });
    }
    if save.was_modded {
        warnings.push(SaveWarning::Modded);
    }
    if scan == Scan::Chunks {
        let chunks = region::chunk_versions(&save.region_dir(OVERWORLD)).map_err(|source| {
            Error::Bundle(spyglass_data::bundle::BundleError::Io {
                path: save.region_dir(OVERWORLD),
                source,
            })
        })?;
        let older = chunks.older_than(save.data_version.unwrap_or(i32::MAX));
        if older > 0 {
            warnings.push(SaveWarning::OlderChunks {
                older,
                total: chunks.total(),
            });
        }
    }
    let location = |l: &spyglass_world::Location| SaveLocation {
        dimension: l.dimension.clone(),
        pos: l.pos,
    };
    Ok(SaveReport {
        save: SaveInfo {
            dir: save.dir.clone(),
            name: save.name.clone(),
            data_version: save.data_version,
            version_name: save.version_name.clone(),
            seed: save.seed,
            generate_structures: save.generate_structures,
            enabled_packs: save.enabled_packs.clone(),
            spawn: save.spawn.as_ref().map(location),
            player: save.player.as_ref().map(location),
        },
        bundle,
        warnings,
    })
}

/// A JSON value with ids namespaced and booleans as 0 or 1, so a save's NBT and a bundle's JSON
/// compare equal when the game would read them the same.
fn normalize(value: &Value) -> Value {
    match value {
        Value::Bool(b) => normalize(&Value::from(u8::from(*b))),
        Value::Number(n) => n
            .as_f64()
            .and_then(serde_json::Number::from_f64)
            .map_or(Value::Null, Value::Number),
        Value::String(s)
            if !s.contains(':')
                && !s.is_empty()
                && s.bytes().all(|b| {
                    b.is_ascii_lowercase() || b.is_ascii_digit() || b"_-./".contains(&b)
                }) =>
        {
            Value::from(format!("minecraft:{s}"))
        }
        Value::Array(items) => Value::Array(items.iter().map(normalize).collect()),
        Value::Object(map) => {
            Value::Object(map.iter().map(|(k, v)| (k.clone(), normalize(v))).collect())
        }
        other => other.clone(),
    }
}

/// The warning for the save's overworld generator, if it isn't the Default preset's.
fn generator_warning(
    save: &spyglass_world::Save,
    bundle: Option<&BundleInfo>,
) -> Result<Option<SaveWarning>> {
    let Some(generator) = save.generators.get(OVERWORLD) else {
        return Ok(Some(SaveWarning::UnsupportedGenerator {
            preset: None,
            generator: "none".into(),
        }));
    };
    let describe = || {
        if let Some(legacy) = generator.get("legacy_generator") {
            let name = legacy
                .get("name")
                .and_then(Value::as_str)
                .unwrap_or("default");
            return format!("legacy {name}");
        }
        let kind = generator.get("type").and_then(Value::as_str).unwrap_or("?");
        match generator.get("settings").and_then(Value::as_str) {
            Some(settings) => format!("{kind} ({settings})"),
            None => kind.to_string(),
        }
    };
    let Some(bundle) = bundle else {
        // Without a bundle there are no presets to compare with; the missing bundle already
        // blocks answers.
        return Ok(None);
    };
    let bundle = Bundle::open(&bundle.dir)?;
    let ours = normalize(generator);
    let mut matched = None;
    let prefix = "data/";
    for path in bundle.manifest().files.keys() {
        let Some(rest) = path.strip_prefix(prefix) else {
            continue;
        };
        let Some((namespace, rest)) = rest.split_once('/') else {
            continue;
        };
        let Some(name) = rest
            .strip_prefix("worldgen/world_preset/")
            .and_then(|n| n.strip_suffix(".json"))
        else {
            continue;
        };
        let id = format!("{namespace}:{name}");
        let preset = bundle.resource("worldgen/world_preset", &id)?;
        let theirs = preset
            .get("dimensions")
            .and_then(|d| d.get(OVERWORLD))
            .and_then(|d| d.get("generator"))
            .map(normalize);
        if theirs.as_ref() == Some(&ours) {
            matched = Some(id);
            break;
        }
    }
    Ok(match matched.as_deref() {
        Some(SUPPORTED_PRESET) => None,
        _ => Some(SaveWarning::UnsupportedGenerator {
            preset: matched,
            generator: describe(),
        }),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn normalized_values_compare_like_the_game() {
        assert_eq!(
            normalize(&json!({"settings": "overworld", "features": false, "height": 1})),
            normalize(&json!({"settings": "minecraft:overworld", "features": 0, "height": 1.0}))
        );
        assert_ne!(
            normalize(&json!({"settings": "minecraft:overworld"})),
            normalize(&json!({"settings": "minecraft:amplified"}))
        );
        // Text that isn't an id is left alone.
        assert_eq!(
            normalize(&json!("3;minecraft:bedrock")),
            json!("3;minecraft:bedrock")
        );
        assert_eq!(normalize(&json!("Seed Check")), json!("Seed Check"));
    }
}
